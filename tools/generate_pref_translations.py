"""Extract C preference display strings for Qt Linguist.

Run from any directory to refresh ui/qt/preference_translation_strings.h, then
run lupdate as usual. The C registration APIs remain independent of Qt, and
preference names, enum values, and serialized UAT records remain unchanged.
Only literal display strings can be extracted; computed/plugin strings fall
back to their original text at runtime.
"""

import argparse
import ast
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / 'ui/qt/preference_translation_strings.h'
TOKEN = re.compile(
    r'//[^\n]*|/\*.*?\*/|"(?:\\.|[^"\\])*"|'
    r"'(?:\\.|[^'\\])*'|[A-Za-z_]\w*|[^\s]", re.S)


def tokens(text):
    return [m.group() for m in TOKEN.finditer(text)
            if not m.group().startswith(('//', '/*'))]


def literal(parts):
    """Join adjacent string literals, without evaluating C expressions."""
    if not parts or any(not part.startswith('"') for part in parts):
        return None
    try:
        return ''.join(ast.literal_eval(part) for part in parts)
    except (SyntaxError, ValueError):
        return None


def arguments(parts, start):
    """Read a call after its opening parenthesis, preserving nested arguments."""
    result, current, depth = [], [], 0
    for index in range(start, len(parts)):
        part = parts[index]
        if part in ('(', '{', '['):
            depth += 1
        if part in (')', '}', ']'):
            if part == ')' and depth == 0:
                return result + [current]
            depth -= 1
        if part == ',' and depth == 0:
            result.append(current)
            current = []
        else:
            current.append(part)
    return []


def extract_strings(text):
    """Extract display arguments and enum descriptions, never preference keys."""
    parts = tokens(text)
    found = set()
    for index, name in enumerate(parts[:-1]):
        if parts[index + 1] != '(':
            continue
        if (name.startswith('prefs_register_') and name.endswith('_preference')
                or name == 'register_string_like_preference'):
            positions = (2, 3)
        elif name == 'prefs_register_module':
            positions = (3, 4)
        elif name == 'prefs_register_subtree':
            positions = (2, 3)
        elif name == 'uat_new':
            positions = (0,)
        elif name.startswith('UAT_FLD_'):
            positions = (2, -1)
        else:
            continue
        args = arguments(parts, index + 2)
        for position in positions:
            if args and -len(args) <= position < len(args):
                value = literal(args[position])
                if value:
                    found.add(value)

    for match in re.finditer(
            r'\benum_val_t\s+\w+\s*\[\s*\]\s*=\s*\{(.*?)\};', text, re.S):
        for row in re.findall(r'\{([^{}]+)\}', match.group(1)):
            fields = arguments(tokens(row) + [')'], 0)
            if len(fields) == 3:
                value = literal(fields[1])
                if value:
                    found.add(value)
    return found


def collect_strings():
    paths = set()
    for folder in ('epan', 'plugins', 'ui', 'wiretap'):
        paths.update((ROOT / folder).rglob('*.c'))
        paths.update((ROOT / folder).rglob('*.cpp'))
    found = set()
    for path in sorted(paths):
        found.update(extract_strings(path.read_text(encoding='utf-8')))
    return sorted(value for value in found if re.search('[A-Za-z]', value))


def generate_header(strings):
    lines = [
        '// Generated by tools/generate_pref_translations.py. Do not edit.',
        '// SPDX-License-Identifier: GPL-2.0-or-later',
        '// lupdate markers only; C preferences must not depend on Qt.',
        '#if 0',
    ]
    for value in strings:
        lines.append('QT_TRANSLATE_NOOP("Preferences", ' +
                     json.dumps(value, ensure_ascii=False) + ')')
    return '\n'.join(lines + ['#endif', ''])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true',
                        help='Fail if the checked-in extraction is out of date')
    args = parser.parse_args()
    generated = generate_header(collect_strings())
    if args.check:
        if OUTPUT.read_text(encoding='utf-8') != generated:
            parser.exit(1, 'Preference translation markers are out of date.\n')
    else:
        OUTPUT.write_text(generated, encoding='utf-8')


if __name__ == '__main__':
    main()
